"""Generate ehfs/src/unicode_data.rs: the Unicode 15.0.0 tables eHFS needs
to compare names (NFC, then simple case folding; 68k_HAL docs/ehfs.md
decisions E1 and E2): canonical combining classes, canonical
decompositions, canonical compositions and simple case foldings.

The input is the Unicode Character Database 15.0.0 (UnicodeData.txt,
CompositionExclusions.txt, CaseFolding.txt and license.txt from
https://www.unicode.org/Public/15.0.0/ucd/), checked by SHA-256 so that the
tables are exactly the ones 68k_HAL's eHFS uses. Nothing is downloaded: the
files are read from a local directory (68k_HAL keeps them in
third_party/downloads/unicode-15.0.0).

Usage: python3 -I tools/gen_casefold.py UCD_DIR [--check]
       python3 -I tools/gen_casefold.py UCD_DIR --compare HAL_UNICODE_DATA_H
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "ehfs", "src", "unicode_data.rs")

SHA256 = {
    "UnicodeData.txt": "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73",
    "CompositionExclusions.txt": "3b019c0a33c3140cbc920c078f4f9af2680ba4f71869c8d4de5190667c70b6a3",
    "CaseFolding.txt": "cdd49e55eae3bbf1f0a3f6580c974a0263cb86a6a08daa10fbf705b4808a56f7",
    "license.txt": "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96",
}


def read(directory, name):
    path = os.path.join(directory, name)
    with open(path, "rb") as f:
        data = f.read()
    if hashlib.sha256(data).hexdigest() != SHA256[name]:
        sys.exit(f"gen_casefold: {path}: SHA-256 is not the Unicode 15.0.0 one")
    return data.decode("utf-8")


def tables(directory):
    ccc, decomp = {}, {}
    for line in read(directory, "UnicodeData.txt").splitlines():
        f = line.split(";")
        cp = int(f[0], 16)
        if int(f[3]) != 0:
            ccc[cp] = int(f[3])
        if f[5] and not f[5].startswith("<"):
            decomp[cp] = [int(x, 16) for x in f[5].split()]
    exclusions = set()
    for line in read(directory, "CompositionExclusions.txt").splitlines():
        line = line.split("#")[0].strip()
        if line:
            exclusions.add(int(line, 16))
    # Primary composites: two-code-point decompositions starting with a
    # starter, not excluded.
    compose = sorted(
        (d[0], d[1], cp)
        for cp, d in decomp.items()
        if len(d) == 2 and cp not in exclusions and ccc.get(d[0], 0) == 0
    )
    fold = []
    for line in read(directory, "CaseFolding.txt").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        code, status, mapping = [x.strip() for x in line.split(";")[:3]]
        if status in ("C", "S"):
            fold.append((int(code, 16), int(mapping, 16)))
    fold.sort()
    flat, index = [], []
    for cp in sorted(decomp):
        index.append((cp, len(flat), len(decomp[cp])))
        flat.extend(decomp[cp])
    return sorted(ccc.items()), index, flat, compose, fold


def render(directory):
    ccc, index, flat, compose, fold = tables(directory)
    lic = read(directory, "license.txt").splitlines()
    out = [
        "// Copyright (C) 2026 YuanChi Hsieh",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "//",
        "// Generated by tools/gen_casefold.py. Do not edit.",
        "//",
        "// The tables are derived from the Unicode Character Database 15.0.0",
        "// (UnicodeData.txt, CompositionExclusions.txt, CaseFolding.txt), whose",
        "// licence (https://www.unicode.org/license.txt) follows:",
        "//",
    ] + [("//   " + line).rstrip() for line in lic] + [
        "",
        "//! Unicode 15.0.0 tables for name comparison (generated).",
        "",
        "/// Canonical combining classes that are not 0: (code point, class).",
        f"pub static CCC: [(u32, u8); {len(ccc)}] = [",
    ]
    for i in range(0, len(ccc), 6):
        out.append("    " + " ".join("(0x%05X, %d)," % c for c in ccc[i:i + 6]))
    out += ["];", "",
            "/// Canonical decompositions: (code point, first index in DECOMP_CPS, length).",
            f"pub static DECOMP: [(u32, u16, u8); {len(index)}] = ["]
    for i in range(0, len(index), 5):
        out.append("    " + " ".join("(0x%05X, %d, %d)," % e for e in index[i:i + 5]))
    out += ["];", "", "/// The code points of the decompositions.",
            f"pub static DECOMP_CPS: [u32; {len(flat)}] = ["]
    for i in range(0, len(flat), 10):
        out.append("    " + " ".join("0x%05X," % c for c in flat[i:i + 10]))
    out += ["];", "",
            "/// Canonical compositions: (first, second, composed), sorted.",
            f"pub static COMPOSE: [(u32, u32, u32); {len(compose)}] = ["]
    for i in range(0, len(compose), 4):
        out.append("    " + " ".join("(0x%05X, 0x%05X, 0x%05X)," % c for c in compose[i:i + 4]))
    out += ["];", "", "/// Simple case folding (CaseFolding.txt status C and S): (from, to).",
            f"pub static FOLD: [(u32, u32); {len(fold)}] = ["]
    for i in range(0, len(fold), 6):
        out.append("    " + " ".join("(0x%05X, 0x%05X)," % c for c in fold[i:i + 6]))
    out += ["];", ""]
    return "\n".join(out), (ccc, index, flat, compose, fold)


def compare(directory, header):
    """Compare the tables with 68k_HAL's unicode_data.h, entry by entry."""
    _, ours = render(directory)
    text = open(header).read()
    names = ["ehfs_ccc", "ehfs_decomp", "ehfs_decomp_cps", "ehfs_compose", "ehfs_fold"]
    for name, table in zip(names, ours):
        body = re.search(name + r"\[\d+\] = \{(.*?)\n\};", text, re.S).group(1)
        numbers = [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", body)]
        flat = [x for entry in table for x in (entry if isinstance(entry, tuple) else (entry,))]
        if numbers != flat:
            sys.exit(f"gen_casefold: {name} differs from 68k_HAL's table")
        print(f"gen_casefold: {name}: {len(table)} entries, identical")


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    directory = sys.argv[1]
    if "--compare" in sys.argv:
        compare(directory, sys.argv[sys.argv.index("--compare") + 1])
        return
    text, (ccc, index, _, compose, fold) = render(directory)
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("gen_casefold: ehfs/src/unicode_data.rs is not what the generator writes")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(f"gen_casefold: {len(ccc)} classes, {len(index)} decompositions, "
          f"{len(compose)} compositions, {len(fold)} case foldings")


main()
