uint32_t mac_roman_to_unicode(uint8_t c)
{
    return c < 0x80 ? c : high[c - 0x80];
}

int mac_roman_from_unicode(uint32_t u)
{
    if (u < 0x80)
        return (int)u;
    for (int i = 0; i < 128; i++)
    {
        if (high[i] == u)
            return 0x80 + i;
    }
    return -1;
}

uint32_t mac_roman_utf8_next(const uint8_t **s, const uint8_t *end)
{
    const uint8_t *p = *s;
    uint8_t c = *p++;
    uint32_t u, min;
    int more;

    if (c < 0x80)
    {
        *s = p;
        return c;
    }
    if ((c & 0xE0) == 0xC0)
        u = c & 0x1Fu, more = 1, min = 0x80;
    else if ((c & 0xF0) == 0xE0)
        u = c & 0x0Fu, more = 2, min = 0x800;
    else if ((c & 0xF8) == 0xF0)
        u = c & 0x07u, more = 3, min = 0x10000;
    else
    {
        *s = p;
        return 0xFFFFFFFFu;
    }
    for (int i = 0; i < more; i++)
    {
        if (p == end || (*p & 0xC0) != 0x80)
        {
            *s = *s + 1;
            return 0xFFFFFFFFu;
        }
        u = u << 6 | (*p++ & 0x3Fu);
    }
    *s = p;
    return u < min || u > 0x10FFFF || (u >= 0xD800 && u <= 0xDFFF) ? 0xFFFFFFFFu : u;
}

uint32_t mac_roman_to_utf8(uint8_t c, uint8_t out[3])
{
    uint32_t u = mac_roman_to_unicode(c);

    if (u < 0x80)
    {
        out[0] = (uint8_t)u;
        return 1;
    }
    if (u < 0x800)
    {
        out[0] = (uint8_t)(0xC0 | u >> 6);
        out[1] = (uint8_t)(0x80 | (u & 0x3F));
        return 2;
    }
    out[0] = (uint8_t)(0xE0 | u >> 12);
    out[1] = (uint8_t)(0x80 | (u >> 6 & 0x3F));
    out[2] = (uint8_t)(0x80 | (u & 0x3F));
    return 3;
}
