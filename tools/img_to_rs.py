"""Turns the icons in assets/ (NAME-SIZE.ppm and NAME-SIZE.pbm) into Rust
data for the kernel and the toolbox (`docs/identity.md`).

Usage: img_to_rs.py ASSETS_DIR OUT_DIR

For every NAME-SIZE.ppm (binary P6, 8-bit; #FF00FF is transparent) with a
NAME-SIZE.pbm (binary P4) beside it, OUT_DIR/NAME-SIZE.rs gets one Rust
expression:

    Icon {
        name: "NAME", size: SIZE,
        palette: &[...],   // 0x00RRGGBB; index 0 is transparent
        runs: &[...],      // the colour image, row by row: (count, index) pairs
        mono: &[...],      // the 1-bit image: rows of SIZE.div_ceil(8) bytes, MSB first
    }

and OUT_DIR/icons.rs lists them all (`pub static NAME_SIZE: Icon =
include!(...)`, and `ALL`). Only the standard library is used (no PIL).
"""
import os
import re
import sys

TRANSPARENT = (0xFF, 0x00, 0xFF)


def read_netpbm(path, magic):
    data = open(path, "rb").read()
    fields = []
    pos = 0
    want = 4 if magic == b"P6" else 3
    while len(fields) < want:
        while data[pos:pos + 1].isspace():
            pos += 1
        if data[pos:pos + 1] == b"#":
            pos = data.index(b"\n", pos) + 1
            continue
        end = pos
        while not data[end:end + 1].isspace():
            end += 1
        fields.append(data[pos:end])
        pos = end
    pos += 1
    if fields[0] != magic:
        sys.exit(f"{path}: not a binary {magic.decode()} file")
    w, h = int(fields[1]), int(fields[2])
    if magic == b"P6" and int(fields[3]) != 255:
        sys.exit(f"{path}: only 8-bit PPM")
    return w, h, data[pos:]


def encode(name, size, ppm, pbm):
    w, h, px = read_netpbm(ppm, b"P6")
    if (w, h) != (size, size):
        sys.exit(f"{ppm}: {w}x{h}, expected {size}x{size}")
    palette = [None]
    indices = []
    for i in range(w * h):
        rgb = tuple(px[i * 3:i * 3 + 3])
        if rgb == TRANSPARENT:
            indices.append(0)
            continue
        value = rgb[0] << 16 | rgb[1] << 8 | rgb[2]
        if value not in palette:
            palette.append(value)
        indices.append(palette.index(value))
    if len(palette) > 256:
        sys.exit(f"{ppm}: more than 255 colours")
    runs = []
    i = 0
    while i < len(indices):
        j = i
        while j < len(indices) and indices[j] == indices[i] and j - i < 255:
            j += 1
        runs += [j - i, indices[i]]
        i = j
    mw, mh, bits = read_netpbm(pbm, b"P4")
    if (mw, mh) != (size, size):
        sys.exit(f"{pbm}: {mw}x{mh}, expected {size}x{size}")
    mono = bits[:((size + 7) // 8) * size]

    def block(values, fmt, per_line):
        lines = []
        for k in range(0, len(values), per_line):
            lines.append("        " + " ".join(fmt.format(v) + "," for v in values[k:k + per_line]))
        return "\n".join(lines)

    pal = [0] + palette[1:]
    return (
        f"// Generated by tools/img_to_rs.py from assets/{name}-{size}.ppm and .pbm;"
        " do not edit.\n// DRAFT artwork: to be replaced by the user's own (assets/README.md).\n"
        "Icon {\n"
        f"    name: \"{name}\",\n"
        f"    size: {size},\n"
        "    palette: &[\n" + block(pal, "0x{:06X}", 6) + "\n    ],\n"
        "    runs: &[\n" + block(runs, "{}", 16) + "\n    ],\n"
        "    mono: &[\n" + block(list(mono), "0x{:02X}", 16) + "\n    ],\n"
        "}\n"
    )


def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    icons = []
    for f in sorted(os.listdir(src)):
        m = re.fullmatch(r"([a-z][a-z0-9-]*)-(\d+)\.ppm", f)
        if not m:
            continue
        name, size = m.group(1), int(m.group(2))
        pbm = os.path.join(src, f"{name}-{size}.pbm")
        if not os.path.exists(pbm):
            sys.exit(f"{pbm} is missing")
        text = encode(name, size, os.path.join(src, f), pbm)
        with open(os.path.join(out, f"{name}-{size}.rs"), "w") as o:
            o.write(text)
        icons.append((name, size))
    with open(os.path.join(out, "icons.rs"), "w") as o:
        o.write("// Generated by tools/img_to_rs.py; do not edit.\n"
                "// DRAFT artwork: to be replaced by the user's own (assets/README.md).\n\n")
        for name, size in icons:
            ident = f"{name.upper().replace('-', '_')}_{size}"
            o.write(f"/// `{name}`, {size}x{size}.\n"
                    f"pub static {ident}: Icon = include!(\"{name}-{size}.rs\");\n")
        o.write("\n/// Every icon.\npub static ALL: &[&Icon] = &[\n")
        for name, size in icons:
            o.write(f"    &{name.upper().replace('-', '_')}_{size},\n")
        o.write("];\n")
    print(f"img_to_rs: {len(icons)} icons")


if __name__ == "__main__":
    main()
