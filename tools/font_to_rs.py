"""Convert a BDF bitmap font into a Rust source file for the kernel console.

Usage: font_to_rs.py <font.bdf> <output.rs> [--first 0x20] [--last 0x7E]

The output defines, for the code points FIRST..=LAST (all must be present):

    pub const WIDTH: usize;          // cell width in pixels
    pub const HEIGHT: usize;         // cell height in pixels
    pub const FIRST: u32;            // first code point
    pub const COUNT: usize;          // number of glyphs
    pub static DATA: [u8; N];        // glyphs, one after another

Each glyph is HEIGHT rows of ceil(WIDTH / 8) bytes; the most significant bit
of a row's first byte is its leftmost pixel. The file is meant for
`include!`, so it contains only items and plain comments.

BDF: Adobe "Glyph Bitmap Distribution Format (BDF) Specification" 2.2.
"""
import argparse
import sys


def parse_bdf(path):
    """Return (cell width, cell height, ascent, comments, {code: rows})."""
    glyphs = {}
    comments = []
    fbb = None
    ascent = None
    with open(path, encoding="ascii", errors="replace") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        words = line.split()
        if not words:
            continue
        key = words[0]
        if key == "COMMENT":
            comments.append(line[len("COMMENT"):].strip())
        elif key == "FONTBOUNDINGBOX":
            fbb = tuple(int(w) for w in words[1:5])
        elif key == "FONT_ASCENT":
            ascent = int(words[1])
        elif key == "STARTCHAR":
            code = None
            bbx = None
            rows = []
            for line in lines:
                words = line.split()
                if words[0] == "ENCODING":
                    code = int(words[1])
                elif words[0] == "BBX":
                    bbx = tuple(int(w) for w in words[1:5])
                elif words[0] == "BITMAP":
                    for line in lines:
                        if line.strip() == "ENDCHAR":
                            break
                        rows.append(int(line.strip(), 16))
                    break
            if code is not None and code >= 0 and bbx is not None:
                glyphs[code] = (bbx, rows)
    if fbb is None or ascent is None:
        sys.exit(f"{path}: missing FONTBOUNDINGBOX or FONT_ASCENT")
    return fbb, ascent, comments, glyphs


def render(fbb, ascent, bbx, rows):
    """Place one glyph in the font cell; return a list of row bit masks
    (bit WIDTH-1 = leftmost pixel)."""
    width, height = fbb[0], fbb[1]
    gw, gh, gx, gy = bbx
    row_bits = (gw + 7) // 8 * 8
    cell = [0] * height
    top = ascent - (gy + gh)  # cell row of the glyph's first bitmap row
    left = gx - fbb[2]
    for i, row in enumerate(rows):
        y = top + i
        if not 0 <= y < height:
            continue
        for x in range(gw):
            if row >> (row_bits - 1 - x) & 1:
                cx = left + x
                if 0 <= cx < width:
                    cell[y] |= 1 << (width - 1 - cx)
    return cell


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bdf")
    ap.add_argument("output")
    ap.add_argument("--first", type=lambda s: int(s, 0), default=0x20)
    ap.add_argument("--last", type=lambda s: int(s, 0), default=0x7E)
    args = ap.parse_args()

    fbb, ascent, comments, glyphs = parse_bdf(args.bdf)
    width, height = fbb[0], fbb[1]
    row_bytes = (width + 7) // 8
    data = []
    for code in range(args.first, args.last + 1):
        if code not in glyphs:
            sys.exit(f"{args.bdf}: no glyph for U+{code:04X}")
        bbx, rows = glyphs[code]
        for row in render(fbb, ascent, bbx, rows):
            row <<= row_bytes * 8 - width
            data.extend(row.to_bytes(row_bytes, "big"))

    count = args.last - args.first + 1
    out = []
    out.append(f"// Generated by tools/font_to_rs.py from {args.bdf.rsplit('/', 1)[-1]}; do not edit.")
    out.append("//")
    for c in comments:
        if c in ("/*", "*/"):
            continue
        out.append(f"// {c.lstrip('* ').rstrip()}".rstrip())
    out.append("")
    out.append("/// Cell width in pixels.")
    out.append(f"pub const WIDTH: usize = {width};")
    out.append("/// Cell height in pixels.")
    out.append(f"pub const HEIGHT: usize = {height};")
    out.append("/// First code point in `DATA`.")
    out.append(f"pub const FIRST: u32 = {args.first:#x};")
    out.append("/// Number of glyphs in `DATA`.")
    out.append(f"pub const COUNT: usize = {count};")
    out.append(f"/// {count} glyphs of {height} rows x {row_bytes} byte(s), MSB = leftmost pixel.")
    out.append("#[rustfmt::skip]")
    out.append(f"pub static DATA: [u8; {len(data)}] = [")
    glyph_bytes = height * row_bytes
    for g in range(count):
        chunk = data[g * glyph_bytes:(g + 1) * glyph_bytes]
        code = args.first + g
        label = chr(code) if 0x20 < code < 0x7F else f"U+{code:04X}"
        out.append(f"    // {label}")
        per_line = 16
        for i in range(0, len(chunk), per_line):
            out.append("    " + " ".join(f"0x{b:02X}," for b in chunk[i:i + per_line]))
    out.append("];")
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
